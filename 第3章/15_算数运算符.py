# ⚠️ Java vs Python 差异：
#   ❌ Java：5 / 2 = 2（整数除法）
#   ✅ Python：5 / 2 = 2.5  ← 永远得 float
#   ✅ Python：5 // 2 = 2   ← 取整用 //

#
# ⚠️ Java vs Python 差异：
#   /  在 Java 里整数除整数得整数（5/2=2）
#   /  在 Python 里永远得 float（5/2=2.5）
#   // 取整 是 Python 独有的（5//2=2）
print(9 + 7)    # 加  # ⭐ 核心语法
print(7 - 2)    # 减
print(3 * 4)    # 乘
print(9 / 3)    # 除（结果是 float）
print(9 // 6)   # 取整（向下取整）
print(9 % 6)    # 取余
print(2 ** 3)   # 指数
